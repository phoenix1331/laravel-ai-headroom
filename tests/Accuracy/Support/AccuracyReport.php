<?php

declare(strict_types=1);

namespace Phoenix1331\AiHeadroom\Tests\Accuracy\Support;

/**
 * Renders accuracy results as the Markdown published in docs/accuracy.md.
 */
final class AccuracyReport
{
    /**
     * @param  array<string, array{model: string, rows: list<array{sample: string, native: int, estimate: int, error: float, calibrated: int, calibrated_error: float}>}>  $results  Provider => results.
     */
    public static function markdown(array $results, string $sdkVersion, string $date): string
    {
        $lines = [
            '# Headroom accuracy',
            '',
            "Generated by `composer test:accuracy` on {$date} against laravel/ai {$sdkVersion}. Each sample is counted by the provider's own counting endpoint (the truth) and by Headroom's local estimate. Error is (estimate - native) / native: positive means Headroom over-counts, which is the safe direction for limits.",
            '',
            '"Calibrated" is the same estimate multiplied by the correction factor self-calibration learned, measured leave-one-out: each sample is corrected by a calibrator trained only on that provider\'s other samples. In use, a safety margin is added on top of the corrected estimate and shrinks towards `safety_margin_floor` as samples accumulate. In an app, calibration learns from your own traffic, which is usually far more uniform than this deliberately mixed corpus.',
            '',
            '## Summary',
            '',
            '| Provider | Model | Mean absolute error | Calibrated | Worst sample |',
            '|---|---|---|---|---|',
        ];

        foreach ($results as $provider => $result) {
            $rows = $result['rows'];
            $worst = $rows === [] ? null : array_reduce($rows, fn (?array $carry, array $row): array => $carry === null || abs($row['error']) > abs($carry['error']) ? $row : $carry);

            $lines[] = sprintf(
                '| %s | `%s` | %s | %s | %s |',
                $provider,
                $result['model'],
                self::percent(self::meanAbsolute(array_column($rows, 'error'))),
                self::percent(self::meanAbsolute(array_column($rows, 'calibrated_error'))),
                $worst === null ? '-' : sprintf('%s (%s)', $worst['sample'], self::signed($worst['error'])),
            );
        }

        foreach ($results as $provider => $result) {
            $lines[] = '';
            $lines[] = "## {$provider} (`{$result['model']}`)";
            $lines[] = '';
            $lines[] = '| Sample | Native | Estimate | Error | Calibrated | Error |';
            $lines[] = '|---|---|---|---|---|---|';

            foreach ($result['rows'] as $row) {
                $lines[] = sprintf(
                    '| %s | %s | %s | %s | %s | %s |',
                    $row['sample'],
                    number_format($row['native']),
                    number_format($row['estimate']),
                    self::signed($row['error']),
                    number_format($row['calibrated']),
                    self::signed($row['calibrated_error']),
                );
            }
        }

        return implode("\n", $lines)."\n";
    }

    /**
     * @param  list<float>  $errors
     */
    private static function meanAbsolute(array $errors): float
    {
        return $errors === [] ? 0.0 : array_sum(array_map(abs(...), $errors)) / count($errors);
    }

    private static function percent(float $fraction): string
    {
        return number_format($fraction * 100, 1).'%';
    }

    private static function signed(float $fraction): string
    {
        return ($fraction > 0 ? '+' : '').number_format($fraction * 100, 1).'%';
    }
}
